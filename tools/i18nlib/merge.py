"""Non-destructive three-way merge and candidate generation."""

from __future__ import annotations

import hashlib
import json
from collections import defaultdict
from difflib import SequenceMatcher
from pathlib import Path
from typing import Any

from .build import _lua_string, _render_translation
from .config import ComponentSpec, Manifest
from .errors import ValidationError
from .lint import Issue, lint_documents, load_policy
from .locale_model import LocaleDocument, LocaleLoader
